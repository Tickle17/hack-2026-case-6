import type { ImageSourcePropType } from 'react-native';
import type { NormRect } from './room';
import type { Point } from '../lib/walkable';

/**
 * Вещи, которые ребёнок накопил, и их место в комнате.
 *
 * Зачем это есть. Копилка без этого — число на экране: полоса
 * заполнилась, вещь «получена», и ничего не изменилось. Накопленное
 * должно стоять дома и работать: в домике питомец сидит, на лежанке
 * спит, с мячом играет. Тогда «копил три дня» превращается в то,
 * что видно каждый день.
 *
 * Данные, а не код: новая цель добавляется строкой и здесь, и в
 * GOALS (ТЗ 2.5.14). Связь по `goalId` — одна цель, одна вещь;
 * это проверяет тест.
 *
 * Координаты — в долях комнаты (0..1), как и вся карта проходимости:
 * они не зависят ни от разрешения картинки, ни от размера экрана.
 *
 * Высота вещи не выдумана, а посчитана из пропорций её картинки: при
 * несовпадении картинка вписывается в коробку с полями, её видимый низ
 * оказывается выше низа коробки — и тень с порядком отрисовки уезжают.
 */

/** Поза питомца у вещи. Именно поза, а не «анимация»: слой комнаты
 *  не знает про питомца и не должен знать. Сопоставление позы с
 *  анимацией живёт в слое питомца. */
export type ThingPose = 'sleep' | 'ball' | 'house';

export type RoomThing = {
  /** Цель, накопив которую ребёнок получает эту вещь. */
  goalId: string;
  /** Левый верхний угол вещи. */
  spot: Point;
  size: { w: number; h: number };
  /** Где стоит питомец, когда пользуется вещью. */
  use: Point;
  pose: ThingPose;
  /**
   * Сквозь вещь нельзя ходить.
   *
   * У лежанки и мяча выключено намеренно: они плоские, питомец по ним
   * проходит, и запирать ими пол незачем.
   */
  blocks: boolean;
  image: ImageSourcePropType;
};

