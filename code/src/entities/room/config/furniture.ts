/** Прямоугольник вещи — для проверки проходимости. */
export function thingRect(thing: RoomThing): NormRect {
  return {
    x: thing.spot.x,
    y: thing.spot.y,
    w: thing.size.w,
    h: thing.size.h,
  };
}
