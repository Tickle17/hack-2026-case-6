/**
 * Оценка заботы за день (UC-5).
 *
 * Раньше здесь же жили стадии «малыш → подросток → взрослый». Их
 * заменил уровень питомца (`level.ts`): у стадий были скрытые баллы,
 * которых ребёнок не видел, а у уровня — опыт, показанный строками
 * на итоге дня. Оценка дня осталась: по ней ведётся история заботы
 * для раздела взрослого.
 *
 */

export type DayCare = {
  /** Всё обязательное на день куплено. */
  mustCovered: boolean;
  /** Факт совпал с планом (с допуском). */
  planKept: boolean;
  /** В копилку что-то ушло. */
  saved: boolean;
};

/** Оценка одного дня: три слагаемых из ТЗ 2.5.10, по одному баллу. */
export function dayCareScore(care: DayCare): number {
  return (
    (care.mustCovered ? 1 : 0) + (care.planKept ? 1 : 0) + (care.saved ? 1 : 0)
  );
}
