import type { Effect } from '../model/types';

/**
 * События дня.
 *
 * Зачем они есть. Критерий 8.4 требует, чтобы механика «требовала
 * выбора, а не сводилась к последовательному нажатию правильных
 * кнопок». Без событий каждый день одинаков: доход тот же, расходы те
 * же, план однажды найденный работает вечно. Событие меняет условия,
 * и план приходится пересматривать.
 *
 * ГЛАВНОЕ ПРАВИЛО: событие — НЕ наказание. Оно привязано к номеру дня,
 * а не к тому, насколько хорошо ребёнок играл. Заказчик прямо запретил
 * болезнь и уход питомца как последствие ошибки; разрешил краткую
 * грусть, если она обратима и не пугает.
 *
 * Поэтому здесь нет ни одного события, которое срабатывает «потому что
 * ты плохо справился». Есть бытовые случайности, понятные ребёнку:
 * испачкался, пришли гости, бабушка прислала гостинец.
 */

export type EventKind =
  /** Появился дополнительный обязательный расход. */
  | 'need'
  /** Неожиданный доход. */
  | 'gift'
  /** Сегодня что-то дешевле. */
  | 'discount';

export type DayEvent = {
  id: string;
  /** День, в который событие происходит. Не состояние — именно день. */
  day: number;
  kind: EventKind;
  title: string;
  /** Что случилось — детской фразой, одно-два предложения. */
  text: string;
  /** Что это значит для сегодняшнего плана. */
  hint: string;
  effects: Effect[];
};

