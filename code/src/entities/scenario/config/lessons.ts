import type { Lesson } from '../model/types';

/**
 * Пул заданий. Содержимое — в `lessons.data.json`, здесь только загрузка.
 *
 * ТЗ 2.5.14 требует, чтобы новое задание добавлялось без переработки
 * логики. Поэтому задания — данные, а не код: текст, варианты ответа
 * и реплики учительницы правит тот, кто пишет контент, и ему не нужен
 * ни TypeScript, ни сборка.
 *
 * ДЕНЬ НЕ ХРАНИТСЯ. Он выводится из порядка: первое задание — второй
 * день (первый уходит на знакомство с питомцем), второе — третий и так
 * далее. Руками проставленные номера рано или поздно расходятся
 * с порядком — появляется пропуск или повтор, — и это приходилось
 * ловить отдельными стражами. Добавленная строка в JSON удлиняет игру
 * ровно на день, и ошибиться негде.
 *
 * ЖЕЛЕЗНОЕ ПРАВИЛО: у каждого задания есть `appliesToday` — момент
 * сегодняшнего дня (план, магазин, итог), где правило пригодится,
 * и напоминание, которое ребёнок увидит в этот момент.
 *
 * `competencyId` ссылается на Единую рамку компетенций
 * (`entities/competency`) — первый из источников, названных в разделе 6
 * ТЗ. Термины и формулировки сверены с просветительским ресурсом
 * Банка России «Финансовая культура» и материалами раздела
 * «Финансовая грамотность» портала «Открытый бюджет города Москвы».
 */

/** Первый день с заданием: первый день уходит на знакомство. */
export const FIRST_LESSON_DAY = 2;

type RawLesson = Omit<Lesson, 'day'>;

/**
 * Файл называется `lessons.data.json`, а не `lessons.json`, — и это
 * не вкусовщина.
 *
 * Metro перебирает расширения в порядке `js, jsx, json, ts, tsx`.
 * При одинаковых именах `import './lessons'` из соседнего модуля
 * подхватывал бы JSON вместо этого файла: сборка проходила, тесты
 * (у них свой порядок) тоже, а приложение падало при запуске
 * на «undefined is not a function».
 */

const data = require('./lessons.data.json') as { lessons: RawLesson[] };

export const LESSONS: Lesson[] = data.lessons.map((lesson, index) => {
  const day = FIRST_LESSON_DAY + index;
  return { ...lesson, day };
});

export function lessonForDay(day: number): Lesson | undefined {
  return LESSONS.find(l => l.day === day);
}

/** Дни, в которые есть задание. По ним сценарий строит школьные дни. */
export function lessonDays(): number[] {
  return LESSONS.map(l => l.day);
}
