import type { GameState } from '../model/types';
import { ITEMS, TASKS } from '../config/registries';
import { goalById, SUGGESTED_GOAL } from '../config/goals';
import { taskBlocker } from './tasks';
import { limitLeft } from './shopping';

/**
 * Подсказки по ходу игры (ТЗ 2.5.1).
 *
 * Отдельной страницы «как играть» нет намеренно: ребёнок 7–11 лет
 * не идёт читать инструкцию, он тыкает. Подсказка появляется там,
 * где нужна, и исчезает, когда шаг сделан.
 *
 * Подсказка не только называет шаг, но и **показывает на кнопку**:
 * «дела внизу» ребёнок ещё должен соотнести с экраном сам, а подсвеченная
 * плитка перевода не требует. Поэтому у подсказки есть цель —
 * идентификатор элемента, вокруг которого экран рисует рамку внимания.
 *
 * Первый день ведём за руку. Дальше подсказки выключаются, а вернуть
 * их можно пунктом меню — о чём и говорит сообщение в конце первого дня.
 *
 * Тон: подсказка предлагает, а не приказывает. «Должен», «обязан»,
 * «нельзя» здесь не встречаются, и это проверяется тестом.
 */

/**
 * Куда может показывать подсказка.
 *
 * Список закрытый: опечатка в идентификаторе означала бы подсказку,
 * которая ни на что не показывает, а заметить это на глаз трудно.
 * Цели дел строятся из реестра, поэтому новое дело правки не требует.
 */
export const HINT_TARGETS: string[] = [
  ...TASKS.map(t => `task.${t.id}`),
  'shop.item',
  'shop.exit',
  'plan.needs',
  'plan.want',
  'plan.goal',
  'plan.save',
];

/**
 * Сколько советуем отложить на «Хочу» в первый день.
 *
 * Ровно на два самых дешёвых лакомства: ребёнок видит, что «Хочу» —
 * это не «когда-нибудь потом», а сегодня, и что на него хватает даже
 * после обязательного. Считается из каталога, а не вписано числом:
 * подешевеет бантик — изменится и совет.
 */
export const SUGGESTED_WANT = ITEMS.filter(i => i.category === 'want')
  .map(i => i.price)
  .sort((a, b) => a - b)
  .slice(0, 2)
  .reduce((sum, p) => sum + p, 0);

export type Hint = {
  text: string;
  /**
   * Элемент, на который показывать. null — показывать не на что:
   * в загадке подсветка выдала бы верный ответ.
   */
  target: string | null;
};

export type HintContext = {
  /** Открыт экран планирования. */
  planning: boolean;
  /** Открыта загадка в школе. */
  riddle?: boolean;
  /** Открыт магазин, и там ещё есть обязательные покупки. */
  shopNeeds?: boolean;
  /** Открыт магазин, обязательное уже куплено. */
  shopTreats?: boolean;
  /** Открыт магазин, но купить сегодня нечего: не на что. */
  shopDone?: boolean;
  /** Сколько дел ещё не сделано сегодня. */
  tasksLeft: number;
};

/**
 * Порядок важен: сначала то, что сейчас на экране поверх всего.
 * Подсказка про дела, показанная поверх магазина, зовёт туда,
 * куда сейчас не попасть.
 */
export function currentHint(state: GameState, ctx: HintContext): Hint | null {
  if (!state.hintsOn) {
    return null;
  }

  if (ctx.riddle) {
    return {
      text: 'Выбери ответ. Ошибиться не страшно — можно ещё раз',
      // Подсветить вариант значило бы решить задачу за ребёнка.
      target: null,
    };
  }

  if (ctx.shopNeeds) {
    return {
      text: 'Сначала возьми нужное',
      target: 'shop.item',
    };
  }

  if (ctx.shopTreats) {
    // Про запланированное на радость напоминаем суммой: без напоминания
    // оно так и останется неистраченным, а вечером «план не сошёлся»
    // станет для ребёнка загадкой.
    const forJoy = limitLeft(state, 'want');
    return forJoy > 0
      ? {
          text: `Обязательное есть. На развлечения планировал ещё ${forJoy} — порадуй питомца`,
          target: 'shop.item',
        }
      : {
          text: 'Обязательное есть. Можно возвращаться домой',
          target: 'shop.exit',
        };
  }

  // Третья фаза магазина. Без неё подсказка проваливалась к делам
  // и звала гулять, хотя ребёнок уже стоит у прилавка.
  if (ctx.shopDone) {
    return {
      text: 'Сегодня купить нечего — можно вернуться домой',
      target: 'shop.exit',
    };
  }

  if (ctx.planning) {
    return {
      text: 'Двигай ползунки или жми + и −, чтобы разложить монеты',
      target: 'plan.needs',
    };
  }

  if (ctx.tasksLeft > 0) {
    return nextStep(state);
  }

  return { text: 'Дела сделаны! Посмотри, что вышло за день', target: null };
}

/**
 * Подсказка по кнопке «Подсказать» в списке дел: показывает, куда нажать,
 * чтобы продолжить. В отличие от автоподсказок работает всегда — ребёнок
 * сам попросил. null — несделанных дел нет.
 */
export function askedTaskHint(state: GameState): Hint | null {
  const left = TASKS.some(t => (state.tasksToday[t.id] ?? 0) < t.perDay);

  return left ? nextStep(state) : null;
}

/** Сообщение в конце первого дня — как вернуть подсказки. */
export const HINTS_OFF_MESSAGE =
  'Дальше играешь сам. Если забудешь, что делать — открой меню ☰ и выбери «Как играть».';

/**
 * Порядок дел, по которому ведём ребёнка.
 *
 * Не произвольный: сначала кормим (корм уже на руках), потом идём
 * гулять — прогулка заканчивается у магазина, где берут набор
 * на завтра, — и только после прогулки купание, потому что на улице
 * питомец пачкается. Поглаживание бесплатно и идёт последним:
 * это не задача, а радость.
 */
const STEP_ORDER = ['feed', 'walk', 'bath', 'pet'];

/** Что делать прямо сейчас — одной фразой. */
const STEP_HINT: Record<string, string> = {
  feed: 'Покорми питомца: тяни миску на пол, он подойдёт сам',
  walk: 'Пора гулять — по дороге зайдём в магазин',
  bath: 'Питомец испачкался на улице — отправь его в ванну',
  pet: 'Погладь питомца — это бесплатно, а он рад',
};

const FALLBACK: Hint = {
  text: 'Дела внизу: тяни их на питомца или нажимай',
  target: null,
};

function nextStep(state: GameState): Hint {
  for (const taskId of STEP_ORDER) {
    const spec = TASKS.find(t => t.id === taskId);
    if (!spec) {
      continue;
    }
    if ((state.tasksToday[taskId] ?? 0) >= spec.perDay) {
      continue;
    }
    const block = taskBlocker(state, taskId);
    if (block?.kind === 'item') {
      /*
       * Нечем — значит следующий шаг не дело, а магазин. Путь называем
       * словами и пальцем не показываем: дорога туда идёт через меню
       * в шапке, а лапка нарисована тычущей ВНИЗ. Над кнопкой шапки
       * места нет, снизу же лапка встаёт вверх ногами и читается
       * как испорченная картинка — хуже, чем её отсутствие.
       */
      return {
        text: `${block.message}: он в магазине, меню ☰`,
        target: null,
      };
    }
    if (block) {
      // Незачем — дело ждёт своего часа, ищем следующее.
      continue;
    }
    return {
      text: STEP_HINT[taskId] ?? FALLBACK.text,
      target: `task.${taskId}`,
    };
  }
  return FALLBACK;
}

/** Что ребёнок уже разложил на экране плана. */
export type PlanDraft = { must: number; want: number };

export type PlanStepOptions = {
  /** Во что обойдётся сегодняшний набор обязательного. */
  mustCost: number;
  /** Весь доход дня. */
  income: number;
  /** Цель уже выбрана. */
  goalChosen: boolean;
  /** Все цели получены — выбирать больше нечего. */
  noGoalsLeft?: boolean;
};

/**
 * Подсказка на экране плана — по шагам.
 *
 * Первый день ведём до конца: ребёнок раскладывает нужное, потом
 * желаемое, потом выбирает цель и сохраняет. Так он один раз проходит
 * весь круг решений под руку, а дальше решает сам.
 *
 * Суммы называются вслух. «Разложи монеты» не говорит, сколько и куда,
 * и ребёнку остаётся гадать или жать наугад.
 */
export function planStepHint(
  draft: PlanDraft,
  opts: PlanStepOptions,
): Hint | null {
  if (opts.mustCost > 0 && draft.must < opts.mustCost) {
    return {
      text: `Положи ${opts.mustCost} в «Обязательное» — это корм и шампунь на завтра`,
      target: 'plan.needs',
    };
  }

  // Советуем «Хочу», только если после обязательного действительно
  // остаётся: звать тратить то, чего нет, — обман.
  const spare = opts.income - draft.must;
  if (draft.want < SUGGESTED_WANT && spare >= SUGGESTED_WANT) {
    return {
      text: `Теперь ${SUGGESTED_WANT} в «Развлечения» — порадуешь питомца в магазине`,
      target: 'plan.want',
    };
  }

  if (!opts.goalChosen && !opts.noGoalsLeft) {
    const goal = goalById(SUGGESTED_GOAL);
    return {
      text: goal
        ? `Выбери, ради чего копим — например, ${goal.title.toLowerCase()}`
        : 'Выбери, ради чего копим',
      target: 'plan.goal',
    };
  }

  return {
    text: 'Всё разложено — копилку пополнишь вечером. Сохраняй!',
    target: 'plan.save',
  };
}
