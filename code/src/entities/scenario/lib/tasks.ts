import type { GameState, ItemSpec } from '../model/types';
import { ITEMS, TASKS } from '../config/registries';

/**
 * Чего не хватает, чтобы сделать дело прямо сейчас.
 *
 * Два разных «нельзя», и их нельзя путать:
 *
 * - **нечем** — не куплен расходник. Это не «кнопка сломалась», а повод
 *   сходить в магазин: ровно та развилка, ради которой игра и сделана.
 * - **незачем** — дело сейчас не нужно: питомец уже поел или уже чистый.
 *
 * Порядок проверок важен. Корм уходит на кормление, поэтому сразу после
 * еды его формально нет — и «нечем» было бы правдой, но правдой
 * бесполезной: покупать сегодня больше нечего, а ребёнка это гонит
 * в магазин. Сначала говорим, что дело уже сделано.
 *
 * Про чистоту спрашиваем саму чистоту, а не «была ли прогулка»: тогда
 * сообщение говорит правду о питомце, а не о порядке кнопок.
 *
 * Оба случая объясняются словами и ведут дальше: дело не прячется,
 * а говорит, что сделать.
 *
 * Поглаживание не требует ничего и доступно всегда: отнимать у ребёнка
 * возможность приласкать питомца из-за пустого кошелька нельзя.
 */

export type TaskBlock =
  | { kind: 'item'; item: ItemSpec; message: string }
  | { kind: 'order'; message: string };

/**
 * Ниже этого значения питомец читается как грязный.
 *
 * Один порог на всю игру: по нему и появляется значок над питомцем,
 * и открывается купание. Два разных числа рано или поздно разошлись бы,
 * и ребёнок видел бы грязного питомца с запертой ванной.
 */
export const DIRTY_BELOW = 60;

/**
 * Что отвечаем, когда дело на сегодня уже сделано.
 *
 * Ласки в списке нет намеренно: она ничего не тратит, и гладить
 * питомца можно сколько угодно раз (docs/ui-kit.md).
 */
const DONE_MESSAGE: Record<string, string> = {
  feed: 'уже поел',
  bath: 'уже купался',
  walk: 'уже гулял',
};

export function taskBlocker(
  state: GameState,
  taskId: string,
): TaskBlock | null {
  const task = TASKS.find(t => t.id === taskId);

  // «Уже сделано» — первым: иначе после кормления игра звала бы
  // покупать корм, которого сегодня больше не нужно.
  const done = DONE_MESSAGE[taskId];
  if (done && task && (state.tasksToday[taskId] ?? 0) >= task.perDay) {
    return { kind: 'order', message: `${state.petName} ${done}` };
  }

  // Ненужность проверяем раньше нехватки: иначе ребёнок купит шампунь
  // и всё равно упрётся в «он уже чистый».
  if (taskId === 'bath' && state.stats.cleanliness >= DIRTY_BELOW) {
    return { kind: 'order', message: `${state.petName} уже очень чистый` };
  }

  if (!task?.requiresItem) {
    return null;
  }
  if ((state.inventory[task.requiresItem] ?? 0) > 0) {
    return null;
  }
  const item = ITEMS.find(i => i.id === task.requiresItem);
  if (!item) {
    return null;
  }
  return {
    kind: 'item',
    item,
    message: `Сначала надо купить ${item.title.toLowerCase()}`,
  };
}
