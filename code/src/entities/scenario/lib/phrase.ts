/**
 * Задание «собери фразу».
 *
 * Учитель называет термин, слова выкладываются вперемешку, ребёнок
 * восстанавливает порядок. В отличие от загадки с вариантами, ответ
 * здесь не выбирают из готового списка, а собирают — этого и требует
 * ТЗ 2.5.8: «задания не ограничиваются выбором ответа из предложенных
 * вариантов».
 *
 * Логика отделена от экрана: перемешивание должно быть проверяемым,
 * а не «как получится».
 */

/** Фраза на слова. Знаки препинания остаются при своих словах. */
export function phraseWords(phrase: string): string[] {
  return phrase.split(/\s+/).filter(Boolean);
}

/**
 * Простой предсказуемый генератор чисел.
 *
 * Не Math.random: порядок слов должен быть ОДИНАКОВЫМ при каждой
 * перерисовке экрана. Со случайным генератором доска пересобиралась бы
 * на каждый кадр, и слово уезжало бы из-под пальца ребёнка.
 */
function nextRandom(seed: number): () => number {
  let value = (seed * 2654435761) % 2147483647;
  if (value <= 0) {
    value += 2147483646;
  }
  return () => {
    value = (value * 16807) % 2147483647;
    return (value - 1) / 2147483646;
  };
}

/**
 * Перемешивает слова так, чтобы получившийся порядок точно отличался
 * от верного: задание, выложенное сразу правильно, ничему не учит.
 *
 * Перебираем зёрна, а не крутим цикл «пока не отличается»: так функция
 * заведомо завершается и на фразе из одного слова, где другого порядка
 * не существует.
 */
export function shuffleWords(words: string[], seed: number): string[] {
  if (words.length < 2) {
    return [...words];
  }

  for (let attempt = 0; attempt < 8; attempt++) {
    const random = nextRandom(seed + attempt * 101 + 1);
    const out = [...words];
    for (let i = out.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [out[i], out[j]] = [out[j], out[i]];
    }
    if (out.some((w, i) => w !== words[i])) {
      return out;
    }
  }

  // Ни одно зерно не дало другого порядка — переставляем два первых
  // слова руками. Случай теоретический, но пустой доски быть не должно.
  const out = [...words];
  [out[0], out[1]] = [out[1], out[0]];
  return out;
}
