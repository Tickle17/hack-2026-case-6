import { shuffleWords, phraseWords } from './phrase';

/**
 * Задание «собери фразу»: учитель называет термин, слова приходят
 * вперемешку, ребёнок восстанавливает порядок.
 *
 * ТЗ 2.5.8 требует, чтобы задания не сводились к выбору варианта из
 * списка. Здесь ответ ребёнок СОБИРАЕТ сам, и вариантов ответа нет.
 */

describe('слова фразы', () => {
  it('фраза распадается на слова', () => {
    expect(phraseWords('Бюджет — это план')).toEqual([
      'Бюджет',
      '—',
      'это',
      'план',
    ]);
  });

  it('лишние пробелы не создают пустых слов', () => {
    expect(phraseWords('  два   слова ')).toEqual(['два', 'слова']);
  });
});

describe('перемешивание', () => {
  const words = ['Бюджет', 'это', 'план', 'расходов'];

  it('слова те же, ни одно не потеряно и не добавлено', () => {
    expect([...shuffleWords(words, 1)].sort()).toEqual([...words].sort());
  });

  it('один и тот же порядок при одном и том же зерне', () => {
    // Иначе доска пересобиралась бы на каждой перерисовке, и слово
    // уезжало бы из-под пальца.
    expect(shuffleWords(words, 7)).toEqual(shuffleWords(words, 7));
  });

  it('разные зёрна дают разный порядок', () => {
    const orders = new Set(
      [1, 2, 3, 4, 5].map(seed => shuffleWords(words, seed).join(' ')),
    );

    expect(orders.size).toBeGreaterThan(1);
  });

  it('никогда не выкладывает слова сразу верно', () => {
    // Задание, решённое до первого касания, ничему не учит.
    for (let seed = 0; seed < 50; seed++) {
      expect(shuffleWords(words, seed)).not.toEqual(words);
    }
  });

  it('фраза из одного слова возвращается как есть', () => {
    // Перемешать нечего — важно не зациклиться в поиске другого порядка.
    expect(shuffleWords(['слово'], 3)).toEqual(['слово']);
  });

  it('два слова всегда меняются местами', () => {
    expect(shuffleWords(['раз', 'два'], 11)).toEqual(['два', 'раз']);
  });
});
