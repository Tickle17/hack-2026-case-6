import { LESSONS } from '@/entities/scenario';

/**
 * Условие задачи обязано помещаться на доску.
 *
 * Доска крупная и текст крупный — значит, места немного. Условие,
 * которое не влезло, обрезается или выдавливает варианты за экран,
 * и задача становится нерешаемой не потому, что трудная.
 *
 * Границы проверены глазами на устройстве: 54 символа занимают три
 * строки и помещаются. Всё, что длиннее, не проверялось, поэтому
 * страж не пускает.
 */

/** Предел, до которого вёрстка доски проверена на устройстве. */
const MAX_PROMPT = 56;

/** Порог перехода на меньший кегль — совпадает с BoardCloseUp. */
const BIG_TEXT_LIMIT = 40;

describe('условия задач помещаются на доску', () => {
  it.each(LESSONS.map(l => [l.id, l.riddle.prompt] as const))(
    '%s',
    (_id, prompt) => {
      expect(prompt.length).toBeLessThanOrEqual(MAX_PROMPT);
    },
  );

  it('короткие условия показываются крупным кеглем', () => {
    const short = LESSONS.filter(l => l.riddle.prompt.length <= BIG_TEXT_LIMIT);
    // Арифметика вида «10 − 3 − 3 − ? = 1» должна быть крупной:
    // ради неё доска и вынесена на передний план.
    expect(short.length).toBeGreaterThan(0);
  });

  it('словесные варианты не смешаны с числовыми в одном задании', () => {
    // Раскладка выбирается на весь набор: числа в ряд, слова в столбик.
    // Смешанный набор верстался бы по длинному варианту, и числа
    // растянулись бы на всю ширину без нужды.
    //
    // Сверяем ТИП, а не длину: «Корм» — короткое слово, но слово,
    // и в один ряд с числами оно не встанет.
    LESSONS.forEach(l => {
      const types = new Set(l.riddle.options.map(o => typeof o.value));
      expect(types.size).toBe(1);
    });
  });

  it('словесный вариант помещается в строку панели', () => {
    // Панель во всю ширину, кегль button: около 30 символов в строку.
    // Длиннее — перенос на третью строку и разъезжающаяся вёрстка.
    //
    // Собираемые фразы сюда не относятся: они никогда не выводятся
    // одной кнопкой — доска разбивает их на слова, и у каждого слова
    // свой предел, он проверяется в lessons.test.ts.
    LESSONS.filter(l => !l.riddle.assemble).forEach(l => {
      l.riddle.options.forEach(o => {
        expect(String(o.value).length).toBeLessThanOrEqual(30);
      });
    });
  });
});
