"""Прогон первых дней игры на живом устройстве.

Что проверяет: игра проходится от приветствия до задания третьего дня,
по дороге нигде не заперев ребёнка, и задание-«вставь слово» доезжает
до доски целиком.

Запуск: python3 tools/e2e/play.py [имя-прогона]
Снимки складываются в /tmp/e2e.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from driver import Fail, Session  # noqa: E402


def intro(s: Session) -> None:
    s.say('приветствие и имя')
    s.fresh_start()
    s.type_name('МИША')
    s.tap('ПРОДОЛЖИТЬ')
    # Анимации выключаем сразу: пока на экране бесконечное движение,
    # иерархию экрана снять невозможно.
    s.calm_mode()
    s.wait('Миша')

    s.say('выбор питомца')
    s.advance_until('КТО ЖЕ ТАМ?')
    s.tap('ЭТО МОЙ ПИТОМЕЦ')


def plan_first_day(s: Session) -> None:
    s.say('план первого дня — по подсказке: 6 на нужное, 3 на хочу')
    s.advance_until('НА ЧТО ПОТРАТИМ')
    s.wait('Положи 6 в «Нужное»')
    s.set_slider('НУЖНОЕ', 6)
    s.wait('Питомцу хватит на всё')
    s.set_slider('ХОЧУ', 3)
    s.tap('ВЫБРАТЬ ЦЕЛЬ', scroll=True)
    s.say('цель — домик, как советует подсказка первого дня')
    s.tap('Домик для питомца')
    s.wait('Всё разложено')
    s.tap('ГОТОВО', scroll=True)
    s.wait('ВСЁ ВЕРНО?')
    s.tap('СОХРАНИТЬ', scroll=True)


def day_one_tasks(s: Session) -> None:
    s.say('дела первого дня: кормим')
    s.wait('тяни миску на пол')
    # Дело выполняется перетаскиванием, а не нажатием: миску ставят
    # на пол, и питомец подходит сам.
    s.drag_to_point('desc:Покормить', 640, 1600)
    # Проверяем по подсказке, а не по галочке: строка списка в дампе
    # разбита на значок и слово, и «☑ Покормить» одним куском там нет.
    s.wait('Пора гулять', timeout=40)

    s.say('идём гулять — по дороге магазин')
    # Прогулка — не перетаскивание, а отдельная сцена: по плитке жмут.
    s.tap('desc:Выгулять')

    s.say('в магазине берём только нужное на завтра')
    # Ждём сам магазин, а не реплику «Дошли до магазина!»: она гаснет
    # сама, и прогон то успевал её застать, то нет. Ждать надо то,
    # что остаётся на экране.
    s.advance_until('Сначала возьми нужное', limit=60)
    for item in ('Корм', 'Шампунь'):
        s.tap(item)
        s.tap('КУПИТЬ')

    # Тратим «Хочу» ровно на запланированные 3 монеты: это второе
    # дополнительное задание дня.
    s.say('тратим «Хочу» ровно по плану — это ещё 2 монеты')
    s.wait('Нужное есть')
    for item in ('Вкусняшка', 'Бантик'):
        s.tap(item)
        s.tap('КУПИТЬ')
    s.say('домой — мыть и гладить')
    s.wait('Можно возвращаться домой')
    s.tap('ДОМОЙ', scroll=True)
    s.wait('отправь его в ванну')
    s.tap('desc:Искупать')
    s.wait('Что дальше?')
    # Порядок задан игрой: каждый предмет тянут на питомца в ванне.
    for step in ('Намочить', 'Намылить', 'Смыть', 'Посушить', 'Причесать'):
        s.drag_to_point(f'desc:{step}', 614, 1400)
    s.say('гладим — это бесплатно')
    s.wait('Погладь питомца')
    s.tap('desc:Погладить')
    s.stroke(640, 1500)
    s.say('итог дня')
    s.advance_until('ЗАКОНЧЕН')
    s.wait('Потратить ровно как задумал')
    s.shot('итог-дня-1')


#: Пул заданий — тот же файл, из которого их берёт игра. Верные
#: ответы прогон не знает «наизусть»: добавили задание — прогон
#: проходит и его, ничего не переписывая.
LESSONS = json.loads(
    (Path(__file__).parents[2] / 'src/entities/scenario/config/lessons.data.json')
    .read_text(encoding='utf-8')
)['lessons']
FIRST_LESSON_DAY = 2


def lesson_day(s: Session, day: int) -> None:
    """Проходит школьный день: доходит до доски и отвечает верно."""
    lesson = LESSONS[day - FIRST_LESSON_DAY]
    riddle = lesson['riddle']
    right = next(o['value'] for o in riddle['options'] if o.get('correct'))

    s.say(f'день {day}: задание «{lesson["kind"]}» — {riddle["prompt"]}')

    if riddle.get('assemble'):
        # Фразу не выбирают, а собирают: слова лежат вперемешку, и
        # нажимать их надо в нужном порядке. Ждём доску по условию и
        # первому слову — вариантов ответа тут нет вовсе.
        words = str(right).split()
        s.advance_until([riddle['prompt'], words[0]], limit=80, every=True)
        s.shot(f'задание-день-{day}-order')
        for word in words:
            # Точное совпадение: слово «это» встречается и внутри
            # условия на доске, и подстрока нашла бы не ту плитку.
            s.tap(f'desc:{word}: поставить в строку')
        s.tap('ПРОВЕРИТЬ')
        s.wait(riddle['onRight'].split('{')[0].strip(), timeout=30)
        s.advance_until(lesson['explanation'].split('{')[0][:24], limit=20)
        s.say(f'фраза собрана: «{right}»')
        return

    # Ждём саму доску — условие и варианты вместе. По одному условию
    # ждать нельзя: реплика учительницы перед заданием начинается
    # теми же словами, и прогон отвечал бы там, где отвечать нечем.
    s.advance_until([riddle['prompt'], str(right)], limit=80, every=True)
    s.shot(f'задание-день-{day}-{lesson["kind"]}')
    s.tap(str(right))
    # Похвала учителя идёт сразу, объяснение — следующей репликой.
    # В текстах стоит подстановка имени, поэтому сверяем только часть
    # до неё: имя у каждого ребёнка своё.
    s.wait(riddle['onRight'].split('{')[0].strip(), timeout=30)
    s.advance_until(lesson['explanation'].split('{')[0][:24], limit=20)
    s.say(f'ответ «{right}» принят, объяснение показано')


def to_shelf(s: Session, tile: str) -> None:
    """Долистывает разговор, пока полка дел снова не видна.

    Между делами вклинивается реплика: мама хвалит за покупки,
    питомец что-то говорит. Пока она на экране, полки нет.
    """
    # Листаем ТОЛЬКО реплики: кнопки «спать» и «следующий день» сюда
    # пускать нельзя, иначе в поисках полки прогон промотает день до
    # конца и окажется в завтрашнем утре.
    s.advance_until(f'desc:{tile}', limit=20, talk_only=True)


#: Сколько откладываем на «Хочу», когда монет хватает.
WANT = 3


def plan_day(s: Session) -> None:
    """Распределяет монеты так, как учит игра: сначала нужное.

    Сумму «нужного» прогон не знает заранее и знать не должен: она
    зависит от того, что осталось с прошлого дня и что понадобится
    завтра. Её называет сам экран — «Нужно ещё минимум N», — и пока
    надпись не сменится на «Питомцу хватит на всё», добавляем.
    """
    s.advance_until('НА ЧТО ПОТРАТИМ', limit=80)
    for _ in range(14):
        if s.screen().find('Питомцу хватит на всё'):
            break
        before = s.screen().slider('НУЖНОЕ')
        s.tap('НУЖНОЕ: добавить монету', scroll=True)
        if s.screen().slider('НУЖНОЕ') == before:
            # Монеты кончились: на всё нужное сегодня не хватает.
            # Это законный ход игры, а не сбой — идём дальше с тем,
            # что есть.
            s.say('на всё нужное монет не хватило — планируем остаток')
            break

    for _ in range(WANT):
        before = s.screen().slider('ХОЧУ')
        s.tap('ХОЧУ: добавить монету', scroll=True)
        if s.screen().slider('ХОЧУ') == before:
            break


def play_day(s: Session) -> None:
    """Обычный день: план, четыре дела, итог.

    Без опоры на подсказки первого дня — со второго дня их нет,
    ребёнок решает сам.
    """
    s.say('план дня')
    plan_day(s)
    s.tap('ГОТОВО', scroll=True)
    s.wait('ВСЁ ВЕРНО?')
    s.tap('СОХРАНИТЬ', scroll=True)

    # Со второго дня подсказок нет — ребёнок решает сам, и прогон
    # тоже: он смотрит на список дел, а не ждёт зелёную плашку.
    s.say('дела дня')
    to_shelf(s, 'Покормить')
    s.drag_to_point('desc:Покормить', 640, 1600)
    s.wait_task('Покормить')
    to_shelf(s, 'Выгулять')
    s.tap('desc:Выгулять')
    # Ждём продавца, а не зелёную подсказку: подсказки живут только
    # в первый день, а продавец на месте всегда.
    s.wait('Продавец', timeout=90)
    for item in ('Корм', 'Шампунь', 'Вкусняшка', 'Бантик'):
        if not s.screen().find(item):
            continue
        s.tap(item)
        # На товар не хватило — подтверждения не будет, карточка
        # просто не откроется. Значит, идём к следующему.
        if s.screen().find('КУПИТЬ'):
            s.tap('КУПИТЬ')
    s.tap('ДОМОЙ', scroll=True)

    s.wait_task('Выгулять')
    to_shelf(s, 'Искупать')
    s.tap('desc:Искупать')
    s.wait('Что дальше?')
    for step in ('Намочить', 'Намылить', 'Смыть', 'Посушить', 'Причесать'):
        s.drag_to_point(f'desc:{step}', 614, 1400)
    s.wait_task('Искупать')

    # Гладить — дело необязательное: день заканчивается, как только
    # сделано нужное для питомца. Поэтому после купания ждём одно из
    # двух — снова полку или уже итог дня.
    for _ in range(4):
        where = s.advance_until(['ЗАКОНЧЕН', 'desc:Погладить'], talk_only=True)
        if where == 'ЗАКОНЧЕН':
            return
        if s.screen().task_mark('Погладить') == '☑':
            return
        s.tap('desc:Погладить')
        s.stroke(640, 1500)


def main() -> int:
    s = Session(sys.argv[1] if len(sys.argv) > 1 else 'play')
    try:
        intro(s)
        plan_first_day(s)
        day_one_tasks(s)
        # Все дни пула, по заданию на день. Список берётся из
        # lessons.data.json: добавили задание — прогон проходит и его.
        for day in range(FIRST_LESSON_DAY, FIRST_LESSON_DAY + len(LESSONS)):
            lesson_day(s, day)
            play_day(s)
    except Fail as e:
        print(f'\nПРОГОН УПАЛ: {e}')
        return 1
    if s.crashes():
        print('\nПРОГОН УПАЛ: приложение падало по дороге')
        return 1
    print('\nпрогон дошёл до конца')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
